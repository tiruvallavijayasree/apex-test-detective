import test, { after } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
// Importing must not run the CLI: if it did, it would fail on the missing default input.
import {
    buildMarkdownReport,
    generateMarkdownReport
} from "../src/analyzer/generateMarkdownReport.js";

const scriptPath = fileURLToPath(
    new URL("../src/analyzer/generateMarkdownReport.js", import.meta.url)
);

// All files are written to an OS temp directory, never to the project's samples folder.
const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "apex-test-detective-md-"));

after(() => {
    fs.rmSync(tempDir, { recursive: true, force: true });
});

const failingReport = {
    project: "Apex Test Detective",
    source: "samples/agentia-apex-test-results.json",
    summary: {
        total: 4,
        passed: 3,
        failed: 1,
        uniqueFailures: 1,
        skipped: 0,
        passRate: "75%"
    },
    failures: [
        {
            testClass: "PaymentCheckerTest",
            testMethod: "testIntentionalAssertionFailure",
            error: "System.AssertException: Assertion Failed: Expected: true, Actual: false",
            category: "ASSERTION_FAILURE",
            diagnosis: "Expected true, but received false.",
            location: {
                failureLocation: {
                    className: "PaymentCheckerTest",
                    methodName: "testIntentionalAssertionFailure",
                    lineNumber: 32,
                    columnNumber: 1
                },
                stackFrames: []
            }
        }
    ]
};

function writeJson(name, value) {
    const file = path.join(tempDir, name);
    fs.writeFileSync(file, typeof value === "string" ? value : JSON.stringify(value), "utf8");
    return file;
}

function runCli(...args) {
    return spawnSync(process.execPath, [scriptPath, ...args], { encoding: "utf8" });
}

test("renders the summary and failure details as Markdown", () => {
    const markdown = buildMarkdownReport(failingReport);

    assert.match(markdown, /^# Apex Test Detective\n/);
    assert.match(markdown, /## Test Run Summary/);
    assert.match(markdown, /- \*\*Source:\*\* samples\/agentia-apex-test-results\.json/);
    assert.match(markdown, /- \*\*Total tests:\*\* 4/);
    assert.match(markdown, /- \*\*Passed:\*\* 3/);
    assert.match(markdown, /- \*\*Failed:\*\* 1/);
    assert.match(markdown, /- \*\*Unique failing tests:\*\* 1/);
    assert.match(markdown, /- \*\*Pass rate:\*\* 75%/);
    assert.match(markdown, /## Failure Analysis/);
    assert.match(markdown, /### 1\. PaymentCheckerTest\.testIntentionalAssertionFailure/);
    assert.match(markdown, /- \*\*Category:\*\* ASSERTION_FAILURE/);
    assert.match(markdown, /- \*\*Line:\*\* 32/);
    assert.match(markdown, /- \*\*Error:\*\* System\.AssertException/);
    assert.match(markdown, /- \*\*Diagnosis:\*\* Expected true, but received false\./);
    assert.match(markdown, /_Generated by Apex Test Detective\./);
    assert.ok(markdown.endsWith("\n"));
});

test("states that no failures were found when the report has none", () => {
    const markdown = buildMarkdownReport({
        summary: { total: 2, passed: 2, failed: 0, passRate: "100%" },
        failures: []
    });

    assert.match(markdown, /No failed tests were found in this report\./);
    assert.doesNotMatch(markdown, /###/);
    assert.doesNotMatch(markdown, /\*\*Source:\*\*/);
    assert.doesNotMatch(markdown, /Unique failing tests/);
});

test("uses readable fallbacks for missing summary and failure fields", () => {
    const markdown = buildMarkdownReport({
        summary: {},
        failures: [{}]
    });

    assert.match(markdown, /- \*\*Total tests:\*\* Unknown/);
    assert.match(markdown, /- \*\*Passed:\*\* Unknown/);
    assert.match(markdown, /- \*\*Failed:\*\* 1/);
    assert.match(markdown, /- \*\*Pass rate:\*\* Unknown/);
    assert.match(markdown, /### 1\. Unknown class\.Unknown method/);
    assert.match(markdown, /- \*\*Category:\*\* UNKNOWN/);
    assert.match(markdown, /- \*\*Line:\*\* Not available/);
    assert.match(markdown, /- \*\*Error:\*\* No error message provided/);
    assert.match(markdown, /- \*\*Diagnosis:\*\* Inspect the exception and stack trace\./);
});

test("numbers multiple failures in order", () => {
    const markdown = buildMarkdownReport({
        summary: { total: 3, passed: 1, failed: 2 },
        failures: [
            { testClass: "AClassTest", testMethod: "first" },
            { testClass: "BClassTest", testMethod: "second" }
        ]
    });

    assert.ok(
        markdown.indexOf("### 1. AClassTest.first") <
        markdown.indexOf("### 2. BClassTest.second")
    );
});

test("rejects input that is not an analysis report", () => {
    const rawSalesforceResults = {
        summary: { testsRan: 4, passing: 3, failing: 1 },
        tests: [{ Outcome: "Fail" }]
    };

    assert.throws(() => buildMarkdownReport(rawSalesforceResults), /not an Apex Test Detective analysis report/);
    assert.throws(() => buildMarkdownReport(null), /not an Apex Test Detective analysis report/);
    assert.throws(() => buildMarkdownReport([]), /not an Apex Test Detective analysis report/);
});

test("rejects a summary that is an array, null, or not an object", () => {
    const invalidSummaries = [[], null, "75%", 4, true];

    for (const summary of invalidSummaries) {
        assert.throws(
            () => buildMarkdownReport({ summary, failures: [] }),
            /not an Apex Test Detective analysis report/,
            `summary ${JSON.stringify(summary)} should be rejected`
        );
    }

    // A missing summary is also rejected, while an empty summary object is still valid.
    assert.throws(
        () => buildMarkdownReport({ failures: [] }),
        /not an Apex Test Detective analysis report/
    );
    assert.doesNotThrow(() => buildMarkdownReport({ summary: {}, failures: [] }));
});

test("CLI exits with an error and writes nothing when the summary is an array", () => {
    const input = writeJson("array-summary.json", { summary: [], failures: [] });
    const output = path.join(tempDir, "array-summary.md");

    const result = runCli(input, output);

    assert.equal(result.status, 1);
    assert.match(result.stderr, /not an Apex Test Detective analysis report/);
    assert.equal(fs.existsSync(output), false);
});

test("keeps a multi-line error message on a single Markdown line", () => {
    const markdown = buildMarkdownReport({
        summary: { total: 1, passed: 0, failed: 1 },
        failures: [
            {
                testClass: "PaymentCheckerTest",
                testMethod: "testMultiLine",
                error: "System.AssertException: first line\n- injected bullet\n# Injected Heading\r\n\r\n## Another Heading\nlast line",
                diagnosis: "Check the data.\n- another bullet\n### Heading in diagnosis"
            }
        ]
    });

    assert.match(
        markdown,
        /^- \*\*Error:\*\* System\.AssertException: first line - injected bullet # Injected Heading ## Another Heading last line$/m
    );
    assert.match(
        markdown,
        /^- \*\*Diagnosis:\*\* Check the data\. - another bullet ### Heading in diagnosis$/m
    );

    // The only headings are the ones the generator creates itself.
    const headings = markdown.split("\n").filter((line) => /^#{1,6}\s/.test(line));
    assert.deepEqual(headings, [
        "# Apex Test Detective",
        "## Test Run Summary",
        "## Failure Analysis",
        "### 1. PaymentCheckerTest.testMultiLine"
    ]);

    // The only bullets are the generator's own labelled fields:
    // 4 summary fields (no source or unique count in this input) + 4 failure fields.
    const bullets = markdown.split("\n").filter((line) => line.startsWith("- "));
    assert.deepEqual(
        bullets.map((line) => line.match(/^- \*\*([A-Za-z ]+):\*\* /)?.[1]),
        ["Total tests", "Passed", "Failed", "Pass rate", "Category", "Line", "Error", "Diagnosis"],
        bullets.join("\n")
    );
});

test("collapses line breaks in other text fields and keeps single-line text unchanged", () => {
    const markdown = buildMarkdownReport({
        source: "samples/results.json\n# Fake heading",
        summary: { total: 1, passed: 0, failed: 1 },
        failures: [
            {
                testClass: "AClassTest\n# Heading",
                testMethod: "unicode\u2028separator",
                category: "ASSERTION_FAILURE",
                error: "Single line error: Expected: true, Actual: false",
                location: { failureLocation: { lineNumber: 0 } }
            }
        ]
    });

    assert.match(markdown, /^- \*\*Source:\*\* samples\/results\.json # Fake heading$/m);
    assert.match(markdown, /^### 1\. AClassTest # Heading\.unicode separator$/m);
    assert.match(markdown, /^- \*\*Error:\*\* Single line error: Expected: true, Actual: false$/m);
    // A line number of 0 is real data and must not fall back to "Not available".
    assert.match(markdown, /^- \*\*Line:\*\* 0$/m);
    assert.doesNotMatch(markdown, /^# Fake heading/m);
    assert.doesNotMatch(markdown, /^# Heading/m);
});

test("falls back to the default text when an error message is only whitespace", () => {
    const markdown = buildMarkdownReport({
        summary: {},
        failures: [{ testClass: "AClassTest", testMethod: "blank", error: " \n \r\n ", diagnosis: "\n" }]
    });

    assert.match(markdown, /^- \*\*Error:\*\* No error message provided$/m);
    assert.match(markdown, /^- \*\*Diagnosis:\*\* Inspect the exception and stack trace\.$/m);
});

test("generateMarkdownReport writes the Markdown file and returns its path", () => {
    const input = writeJson("fn-report.json", failingReport);
    const output = path.join(tempDir, "nested", "dir", "fn-report.md");

    const result = generateMarkdownReport(input, output);

    assert.equal(result, output);
    assert.equal(fs.readFileSync(output, "utf8"), buildMarkdownReport(failingReport));
});

test("CLI writes Markdown to the output file instead of printing JSON", () => {
    const input = writeJson("cli-report.json", failingReport);
    const output = path.join(tempDir, "cli-report.md");

    const result = runCli(input, output);

    assert.equal(result.status, 0, result.stderr);
    assert.equal(result.stdout.trim(), `Markdown report created: ${output}`);
    assert.doesNotMatch(result.stdout, /"summary"/);

    const markdown = fs.readFileSync(output, "utf8");
    assert.match(markdown, /^# Apex Test Detective/);
    assert.match(markdown, /### 1\. PaymentCheckerTest\.testIntentionalAssertionFailure/);
});

test("CLI exits with an error and writes nothing when the input is missing", () => {
    const output = path.join(tempDir, "missing-input.md");

    const result = runCli(path.join(tempDir, "does-not-exist.json"), output);

    assert.equal(result.status, 1);
    assert.match(result.stderr, /Markdown report failed: Report not found/);
    assert.equal(fs.existsSync(output), false);
});

test("CLI exits with an error and writes nothing when the input is invalid JSON", () => {
    const input = writeJson("invalid.json", "{ not valid json");
    const output = path.join(tempDir, "invalid.md");

    const result = runCli(input, output);

    assert.equal(result.status, 1);
    assert.match(result.stderr, /Could not parse .* as JSON/);
    assert.equal(fs.existsSync(output), false);
});

