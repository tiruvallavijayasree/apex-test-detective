
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_INPUT = "samples/analysis-report.json";
const DEFAULT_OUTPUT = "samples/analysis-report.md";

function isPlainObject(value) {
    return value !== null && typeof value === "object" && !Array.isArray(value);
}

/**
 * Collapses line breaks (and the whitespace around them) into single spaces so
 * multi-line text, such as an Apex error or stack trace, stays on one Markdown
 * line and cannot start a new heading, bullet, or other block.
 */
function toSingleLine(value) {
    return String(value ?? "")
        .replace(/\s*[\r\n\u2028\u2029]+\s*/g, " ")
        .trim();
}

/**
 * Validates that the parsed JSON is an Apex Test Detective analysis report
 * (the output of analyzeSalesforceResults.js), not raw Salesforce results.
 * Both the report and its 'summary' must be plain objects (not arrays or null).
 */
function assertAnalysisReport(report) {
    if (
        !isPlainObject(report) ||
        !isPlainObject(report.summary) ||
        !Array.isArray(report.failures)
    ) {
        throw new Error(
            "Input is not an Apex Test Detective analysis report " +
            "(expected a 'summary' object and a 'failures' array). " +
            "Run analyzeSalesforceResults.js first."
        );
    }
}

/**
 * Builds the Markdown text for an analysis report object.
 * Pure function: performs no file or console I/O.
 */
export function buildMarkdownReport(report) {
    assertAnalysisReport(report);

    const summary = report.summary;
    const failures = report.failures;

    const lines = [
        "# Apex Test Detective",
        "",
        "## Test Run Summary",
        ""
    ];

    const source = toSingleLine(report.source);

    if (source) {
        lines.push(`- **Source:** ${source}`);
    }

    lines.push(
        `- **Total tests:** ${summary.total ?? "Unknown"}`,
        `- **Passed:** ${summary.passed ?? "Unknown"}`,
        `- **Failed:** ${summary.failed ?? failures.length}`
    );

    if (summary.uniqueFailures !== undefined) {
        lines.push(`- **Unique failing tests:** ${summary.uniqueFailures}`);
    }

    lines.push(
        `- **Pass rate:** ${summary.passRate ?? "Unknown"}`,
        "",
        "## Failure Analysis",
        ""
    );

    if (failures.length === 0) {
        lines.push("No failed tests were found in this report.", "");
    } else {
        for (const [index, failure] of failures.entries()) {
            const location = failure?.location?.failureLocation || {};
            const testClass = toSingleLine(failure?.testClass) || "Unknown class";
            const testMethod = toSingleLine(failure?.testMethod) || "Unknown method";
            const category = toSingleLine(failure?.category) || "UNKNOWN";
            const lineNumber = toSingleLine(location.lineNumber) || "Not available";
            const error = toSingleLine(failure?.error) || "No error message provided";
            const diagnosis =
                toSingleLine(failure?.diagnosis) || "Inspect the exception and stack trace.";

            lines.push(
                `### ${index + 1}. ${testClass}.${testMethod}`,
                "",
                `- **Category:** ${category}`,
                `- **Line:** ${lineNumber}`,
                `- **Error:** ${error}`,
                `- **Diagnosis:** ${diagnosis}`,
                ""
            );
        }
    }

    lines.push(
        "---",
        "",
        "_Generated by Apex Test Detective. Diagnoses are suggestions and should be verified against the Apex code._",
        ""
    );

    return lines.join("\n");
}

/**
 * Reads an analysis report JSON file and writes the Markdown report.
 * Returns the output path. Throws on a missing, unreadable, or invalid input.
 */
export function generateMarkdownReport(
    inputFile = DEFAULT_INPUT,
    outputFile = DEFAULT_OUTPUT
) {
    if (!fs.existsSync(inputFile)) {
        throw new Error(`Report not found: ${inputFile}`);
    }

    let report;

    try {
        report = JSON.parse(fs.readFileSync(inputFile, "utf8"));
    } catch (error) {
        throw new Error(`Could not parse ${inputFile} as JSON: ${error.message}`);
    }

    const markdown = buildMarkdownReport(report);

    fs.mkdirSync(path.dirname(path.resolve(outputFile)), { recursive: true });
    fs.writeFileSync(outputFile, markdown, "utf8");

    return outputFile;
}

function isMainModule() {
    if (!process.argv[1]) return false;

    try {
        return (
            fs.realpathSync(process.argv[1]) ===
            fs.realpathSync(fileURLToPath(import.meta.url))
        );
    } catch {
        return false;
    }
}

// Run as a CLI only when executed directly, not when imported (for example, by tests).
if (isMainModule()) {
    try {
        const outputFile = generateMarkdownReport(
            process.argv[2] || DEFAULT_INPUT,
            process.argv[3] || DEFAULT_OUTPUT
        );

        console.log(`Markdown report created: ${outputFile}`);
    } catch (error) {
        console.error(`Markdown report failed: ${error.message}`);
        process.exitCode = 1;
    }
}
