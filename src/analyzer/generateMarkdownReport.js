
import fs from "node:fs";

const inputFile =
    process.argv[2] || "samples/analysis-report.json";

const outputFile =
    process.argv[3] || "samples/analysis-report.md";

if (!fs.existsSync(inputFile)) {
    console.error(`Report not found: ${inputFile}`);
    process.exit(1);
}

const report = JSON.parse(
    fs.readFileSync(inputFile, "utf8")
);

const summary = report.summary || {};
const failures = report.failures || [];

const lines = [
    "# Apex Test Detective",
    "",
    "## Test Run Summary",
    "",
    `- **Total tests:** ${summary.total ?? "Unknown"}`,
    `- **Passed:** ${summary.passed ?? "Unknown"}`,
    `- **Failed:** ${summary.failed ?? failures.length}`,
    `- **Pass rate:** ${summary.passRate ?? "Unknown"}`,
    "",
    "## Failure Analysis",
    ""
];

if (failures.length === 0) {
    lines.push("No failed tests were found in this report.");
} else {
    for (const [index, failure] of failures.entries()) {
        const location = failure.location?.failureLocation || {};

        lines.push(
            `### ${index + 1}. ${failure.testClass || "Unknown class"}.${failure.testMethod || "Unknown method"}`,
            "",
            `- **Category:** ${failure.category || "UNKNOWN"}`,
            `- **Line:** ${location.lineNumber ?? "Not available"}`,
            `- **Error:** ${failure.error || "No error message provided"}`,
            `- **Diagnosis:** ${failure.diagnosis || "Inspect the exception and stack trace."}`,
            ""
        );
    }
}

lines.push(
    "---",
    "",
    "_Generated by Apex Test Detective. Diagnoses are suggestions and should be verified against the Apex code._",
    ""
);

fs.writeFileSync(outputFile, lines.join("\n"), "utf8");

console.log(`Markdown report created: ${outputFile}`);
